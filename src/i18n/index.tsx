const LocaleContext = createContext<I18nContextValue | undefined>(undefined);

const getDefaultLocale = (): SupportedLocale => {
  if (typeof window === "undefined") return "fr";
  const stored = window.localStorage.getItem(STORAGE_KEY) as SupportedLocale | null;
  if (stored && Object.keys(translations).includes(stored)) {
    return stored;
  }
  const browserLocale = navigator.language.slice(0, 2).toLowerCase();
  if (browserLocale === "en" || browserLocale === "es" || browserLocale === "zh") return browserLocale as SupportedLocale;
  return "fr";
};

const lookup = (locale: SupportedLocale, key: string): string => {
  const findInLocale = (loc: SupportedLocale): string | null => {
    const keys = key.split(".");
    let current: string | TranslationMap | undefined = translations[loc];
    for (const part of keys) {
      if (typeof current === "object" && current !== null && part in current) {
        current = current[part] as string | TranslationMap;
      } else {
        return null;
      }
    }
    return typeof current === "string" ? current : null;
  };

  const translated = findInLocale(locale);
  if (translated !== null) return translated;

  if (locale !== "fr") {
    const fallback = findInLocale("fr");
    if (fallback !== null) return fallback;
  }

  return key;
};

const interpolate = (value: string, params?: Record<string, string | number>) => {
  if (!params) return value;
  return Object.entries(params).reduce((acc, [param, replacement]) => acc.replace(new RegExp(`\\{\\{\\s*${param}\\s*\\}\\}`, "g"), String(replacement)), value);
};

const setGoogleTranslateCookie = (locale: SupportedLocale) => {
  if (typeof window === "undefined") return;

  if (locale === "fr") {
    // Clear googtrans cookies so original French text is preserved untouched
    document.cookie = "googtrans=; expires=Thu, 01 Jan 1970 00:00:00 UTC; path=/;";
    document.cookie = `googtrans=; expires=Thu, 01 Jan 1970 00:00:00 UTC; path=/; domain=${window.location.hostname};`;
    
    const selectElem = document.querySelector(".goog-te-combo") as HTMLSelectElement | null;
    if (selectElem && selectElem.value && selectElem.value !== "fr") {
      selectElem.value = "fr";
      selectElem.dispatchEvent(new Event("change"));
    }
    return;
  }

  const targetLang = locale;
  const cookieValue = `/fr/${targetLang}`;
  document.cookie = `googtrans=${cookieValue}; path=/; domain=${window.location.hostname}`;
  document.cookie = `googtrans=${cookieValue}; path=/`;

  const selectElem = document.querySelector(".goog-te-combo") as HTMLSelectElement | null;
  if (selectElem && selectElem.value !== targetLang) {
    selectElem.value = targetLang;
    selectElem.dispatchEvent(new Event("change"));
  }
};

export const LocaleProvider = ({ children }: { children: ReactNode }) => {
  const [locale, setLocale] = useState<SupportedLocale>(getDefaultLocale);

  useEffect(() => {
    window.localStorage.setItem(STORAGE_KEY, locale);
    document.documentElement.lang = locale;
    setGoogleTranslateCookie(locale);
  }, [locale]);

  const value = useMemo(() => ({ locale, setLocale }), [locale]);

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
};

export const useLocale = () => {
  const context = useContext(LocaleContext);
  if (!context) {
    throw new Error("useLocale must be used within a LocaleProvider");
  }
  return context;
};

export const useTranslation = () => {
  const { locale, setLocale } = useLocale();

  const t = (key: string, params?: Record<string, string | number>) => {
    const translated = lookup(locale, key);
    return interpolate(translated, params);
  };

  return { t, locale, setLocale };
};

